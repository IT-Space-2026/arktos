#!/usr/bin/env python3
"""Generate the no-servo flatpak flavor from the canonical manifest.

SRV01/flavors: com.arktos_browser.Arktos.yaml is the canonical (servo)
manifest — the only file edited by hand.  This script derives the
QtWebEngine-only sibling so both flavors can be installed side-by-side:

  com.arktos_browser.ArktosNoServo.yaml              (repo root)
  flatpak/com.arktos_browser.ArktosNoServo.metainfo.xml

Transformations applied:
  * app-id -> com.arktos_browser.ArktosNoServo
  * sdk-extensions: drop org.freedesktop.Sdk.Extension.llvm21 (only
    servo-embed's mozjs-sys bindgen needs clang/libclang)
  * modules: drop the servo-embed module entirely (its ~700-crate
    build, vendored cargo-sources-servo.json fragment and /app/lib
    install all go with it)
  * arktos module build-commands: drop the two servo lines (the
    artifact staging copy and the x86_64 link-proof — both reference
    libservo_embed), retarget the metainfo install at the generated
    NoServo metainfo, and suffix the desktop Name= so the two
    side-by-side launchers are distinguishable
  * metainfo xml: id, launchable desktop-id and <name> rewritten to
    the NoServo identity, plus a description paragraph noting the
    build ships QtWebEngine only

  gen-flavor-manifest.py            write both files
  gen-flavor-manifest.py --check    regenerate in memory, exit 1 if
                                    the committed files drifted
"""

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CANON_MANIFEST = ROOT / "com.arktos_browser.Arktos.yaml"
CANON_METAINFO = ROOT / "flatpak" / "com.arktos_browser.Arktos.metainfo.xml"
OUT_MANIFEST = ROOT / "com.arktos_browser.ArktosNoServo.yaml"
OUT_METAINFO = ROOT / "flatpak" / "com.arktos_browser.ArktosNoServo.metainfo.xml"

NOSERVO_ID = "com.arktos_browser.ArktosNoServo"
SERVO_ID = "com.arktos_browser.Arktos"
NAME_SUFFIX = " (No Servo)"

HEADER = """\
# GENERATED by flatpak/gen-flavor-manifest.py — DO NOT EDIT.
# The canonical manifest is com.arktos_browser.Arktos.yaml (servo
# flavor); this is the derived QtWebEngine-only sibling installed
# side-by-side under its own app-id.  Re-run the generator after
# touching the canonical manifest; `pkg-flatpak.sh verify` and CI
# keep this file in sync.
"""

DESCRIPTION_NOTE = (
    "This is the NoServo flavor of Arktos: the same browser built "
    "without the experimental Servo engine backend — QtWebEngine only."
)


def gen_manifest() -> str:
    doc = yaml.safe_load(CANON_MANIFEST.read_text(encoding="utf-8"))

    assert doc["app-id"] == SERVO_ID, doc["app-id"]
    doc["app-id"] = NOSERVO_ID

    doc["sdk-extensions"] = [
        ext for ext in doc["sdk-extensions"] if "llvm" not in ext
    ]

    doc["modules"] = [
        mod for mod in doc["modules"] if mod.get("name") != "servo-embed"
    ]

    arktos = next(m for m in doc["modules"] if m.get("name") == "arktos")
    commands = arktos["build-commands"]
    commands = [
        c for c in commands
        if "libservo_embed" not in c and "servo-embed" not in c
    ]
    commands = [
        c.replace(f"{SERVO_ID}.metainfo.xml", f"{NOSERVO_ID}.metainfo.xml")
        for c in commands
    ]
    # Suffix every Name= line (incl. localized Name[xx]=) so the two
    # side-by-side launchers read differently; flatpak-builder renames
    # the file to <app-id>.desktop afterwards.
    commands.append(
        'sed -i -E "s/^(Name(\\[[^]]*\\])?=.*)$/\\1'
        + NAME_SUFFIX
        + '/" /app/share/applications/arktos.desktop'
    )
    arktos["build-commands"] = commands

    body = yaml.safe_dump(doc, sort_keys=False, width=4096,
                          default_flow_style=False)
    return HEADER + body


def gen_metainfo() -> str:
    text = CANON_METAINFO.read_text(encoding="utf-8")
    text = text.replace(f"<id>{SERVO_ID}</id>", f"<id>{NOSERVO_ID}</id>")
    text = text.replace(
        f"<launchable type=\"desktop-id\">{SERVO_ID}.desktop</launchable>",
        f"<launchable type=\"desktop-id\">{NOSERVO_ID}.desktop</launchable>",
    )
    text = text.replace("<name>Arktos</name>",
                        f"<name>Arktos{NAME_SUFFIX}</name>", 1)
    text = text.replace(
        "  </description>",
        f"    <p>\n      {DESCRIPTION_NOTE}\n    </p>\n  </description>",
        1,
    )
    # sanity: the rewritten xml must still parse and carry no servo id
    root = ET.fromstring(text)
    assert root.find("id").text == NOSERVO_ID
    assert f"{SERVO_ID}.desktop" not in text
    return text


def main() -> int:
    check = "--check" in sys.argv[1:]
    outputs = {OUT_MANIFEST: gen_manifest(), OUT_METAINFO: gen_metainfo()}
    drift = False
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                print(f"DRIFT: {path} — re-run flatpak/gen-flavor-manifest.py",
                      file=sys.stderr)
                drift = True
        else:
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path}")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
