#!/usr/bin/env python3
"""AUDIT02 dedup — diff STAT02 analyzer findings against the STAT01
triaged baseline and emit .devin/STAT02-findings.txt.

Inputs:
  $1  STAT02 gcc findings   (build tree gcc-findings.txt)
  $2  STAT02 clang findings (build tree clang-findings.txt)
  $3  STAT01 report         (.devin/STAT01-report.md)
  $4  output                (.devin/STAT02-findings.txt)

A finding "carries over" when (file, checker) already appeared in
STAT01 — line numbers are ignored because the tree moved massively
since Oct 10.  Findings whose checker belongs to a blanket-justified
family (uic/moc operator-new CWE-690 noise, '<unknown>' uninit) carry
over by family even at new sites; every other new (file, checker) pair
is listed individually for slice-B triage.
"""
import re, sys, collections

GCC_F, CLANG_F, STAT01_MD, OUT = sys.argv[1:5]


def parse_findings(path):
    secs, cur = {}, None
    for line in open(path, errors='replace'):
        line = line.rstrip('\n')
        if line.startswith('== '):
            cur = line.strip('= ').strip()
            secs[cur] = []
        elif cur and line:
            secs[cur].append(line)
    return secs


def parse_stat01(path):
    pairs = set()  # (file, checker) already triaged
    rx = re.compile(r'^([^:]+\.[a-zA-Z]+):\d+:\d+: warning:.*'
                    r'(\[-Wanalyzer-[a-z-]+\]|\[[a-zA-Z]+\.[a-zA-Z.]+\])\s*$')
    for line in open(path, errors='replace'):
        m = rx.match(line.rstrip())
        if m:
            pairs.add((m.group(1), m.group(2)))
    return pairs


CHECKER = re.compile(r'(\[-Wanalyzer-[a-z-]+\]|\[[a-zA-Z]+\.[a-zA-Z.]+\])\s*$')
LOC = re.compile(r'^([^:]+):(\d+):(\d+):')


def key(rec):
    m = CHECKER.search(rec)
    lm = LOC.match(rec)
    return (lm.group(1), m.group(1) if m else '?')


def family(rec):
    """Blanket-triaged STAT01 families — new sites need no re-triage."""
    if 'operator new' in rec and ('possible-null' in rec):
        return 'gcc-operator-new-CWE690'
    if 'use of uninitialized value' in rec and '\u2018<unknown>\u2019' in rec:
        return 'gcc-uninit-unknown'
    if 'uninitialized value' in rec and '<unknown>' in rec:
        return 'gcc-uninit-unknown'
    lm = LOC.match(rec)
    if lm and ('/.ui/' in lm.group(1) or '/.moc/' in lm.group(1)
               or lm.group(1).startswith('src/.ui/')
               or lm.group(1).startswith('src/.moc/')):
        return 'generated-uic-moc'
    return None


def split_new(secs, base):
    carry, fam, new = [], collections.Counter(), []
    for rec in secs.get('in-tree', []):
        f = family(rec)
        if f:
            fam[f] += 1
        elif key(rec) in base:
            carry.append(rec)
        else:
            new.append(rec)
    return carry, fam, new


base = parse_stat01(STAT01_MD)
gcc = parse_findings(GCC_F)
clng = parse_findings(CLANG_F)
g_carry, g_fam, g_new = split_new(gcc, base)
c_carry, c_fam, c_new = split_new(clng, base)

with open(OUT, 'w') as o:
    w = o.write
    w('# STAT02 — deduped findings vs STAT01 baseline\n')
    w('# Generated by .devin/AUDIT02-dedup.py; full raw lists in'
      ' .devin/STAT02-report.md\n#\n')
    w('# Carry-over rule: (file, checker) pair seen in STAT01-report.md,'
      ' or a member of a\n# blanket-justified family (uic/moc-generated,'
      ' operator-new CWE-690, <unknown> uninit).\n\n')
    w('## Summary\n\n')
    w('GCC  -fanalyzer in-tree: %d total — %d carry-over sites,'
      ' %d family-member, %d NEW\n'
      % (len(gcc.get('in-tree', [])), len(g_carry), sum(g_fam.values()),
         len(g_new)))
    w('clang --analyze  in-tree: %d total — %d carry-over sites,'
      ' %d family-member, %d NEW\n\n'
      % (len(clng.get('in-tree', [])), len(c_carry), sum(c_fam.values()),
         len(c_new)))
    if g_fam or c_fam:
        w('## Family-member findings (blanket-justified in'
          ' STAT01-triage.md — no re-triage)\n\n')
        for k, v in sorted((g_fam + c_fam).items()):
            w('  %s: %d\n' % (k, v))
        w('\n')
    w('## NEW findings needing triage (AUDIT03)\n\n')
    w('### GCC -fanalyzer (%d)\n\n' % len(g_new))
    w('\n'.join(g_new) + ('\n' if g_new else 'none\n'))
    w('\n### clang --analyze (%d)\n\n' % len(c_new))
    w('\n'.join(c_new) + ('\n' if c_new else 'none\n'))
    w('\n## Carry-over sites (%d gcc, %d clang) — same (file,checker)'
      ' as STAT01\n\n' % (len(g_carry), len(c_carry)))
    w('### gcc\n\n' + '\n'.join(g_carry) + '\n\n### clang\n\n'
      + '\n'.join(c_carry) + '\n')
print('new: %d gcc, %d clang' % (len(g_new), len(c_new)))
